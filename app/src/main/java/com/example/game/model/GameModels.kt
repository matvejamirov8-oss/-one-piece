/**
 * Axis-aligned bounding box in virtual pixel world coordinates.
 * Used for physics grounding, player/enemy hurtboxes, projectiles, and attack hitboxes.
 */
data class Rect2D(
    val x: Float,
    val y: Float,
    val width: Float,
    val height: Float
) {
    val right: Float get() = x + width
    val bottom: Float get() = y + height
    val centerX: Float get() = x + width * 0.5f
    val centerY: Float get() = y + height * 0.5f

    fun intersects(other: Rect2D): Boolean {
        return x < other.right && right > other.x && y < other.bottom && bottom > other.y
    }
}


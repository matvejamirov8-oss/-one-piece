data class EastBlueAiStepResult(
    val enemy: EnemyState,
    val actions: List<EastBlueAiAction> = emptyList()
)

/**
 * Basic finite state machine AI for East Blue enemies (Marine Soldiers, Marine Riflemen, Pirate Bandits).
 * Handles:
 * - [EnemyBehaviorState.PATROL]: Pacing around [EnemyState.patrolOriginX] until Luffy, Zoro, or another hero enters detection range.
 * - [EnemyBehaviorState.CHASE]: Closing in (or kiting to preferred firing range for Riflemen), or returning to patrol if the hero retreats.
 * - [EnemyBehaviorState.WINDUP] -> [EnemyBehaviorState.ATTACK] -> [EnemyBehaviorState.RECOVER]: Telegraphed melee/ranged attacks with optional combo follow-ups.
 */
class EastBlueEnemyAi(
    val config: EastBlueEnemyAiConfig = EastBlueEnemyAiConfig()
) {
    companion object {
        fun forKind(kind: EnemyKind): EastBlueEnemyAi =
            EastBlueEnemyAi(EastBlueEnemyAiConfig.forKind(kind))
    }

    fun step(enemy: EnemyState, target: LuffyState, dt: Float): EastBlueAiStepResult {
        val dxToTarget = target.x - enemy.x
        val absDx = abs(dxToTarget)
        val dirToTarget = if (dxToTarget >= 0f) FacingDirection.RIGHT else FacingDirection.LEFT
        val t = enemy.stateTimer + dt
        val actions = mutableListOf<EastBlueAiAction>()

        // High-profile Straw Hat captains/swordsmen (Luffy in Gear 4 or Zoro in King of Hell) draw slightly earlier aggro
        val isHighAlertHero = (target.activeHero == PlayableHero.LUFFY && target.gear4Active) ||
            (target.activeHero == PlayableHero.ZORO && target.zoroHellActive)
        val effectiveDetectRange = if (isHighAlertHero) config.detectRange + 36f else config.detectRange
        val inAttackRange = absDx in config.attackRangeMin..config.attackRangeMax

        val nextEnemy = when (enemy.behavior) {
            EnemyBehaviorState.PATROL -> {
                if (isTargetEngaged(target, absDx, effectiveDetectRange)) {
                    enemy.copy(
                        behavior = EnemyBehaviorState.CHASE,
                        facing = dirToTarget,
                        stateTimer = 0f
                    )
                } else {
                    stepPatrol(enemy, dt, t)
                }
            }

            EnemyBehaviorState.CHASE -> {
                when {
                    absDx > config.loseAggroRange -> {
                        enemy.copy(
                            behavior = EnemyBehaviorState.PATROL,
                            patrolOriginX = enemy.x,
                            stateTimer = 0f
                        )
                    }
                    inAttackRange && enemy.attackCooldown <= 0f && enemy.isGrounded -> {
                        enemy.copy(
                            vx = 0f,
                            facing = dirToTarget,
                            behavior = EnemyBehaviorState.WINDUP,
                            stateTimer = 0f,
                            comboStep = 0,
                            attackHitApplied = false
                        )
                    }
                    else -> {
                        val targetVx = when {
                            config.isRanged && absDx < config.preferredMinDistance ->
                                -dirToTarget.sign * enemy.kind.moveSpeed * 0.92f
                            absDx > config.preferredMaxDistance ->
                                dirToTarget.sign * enemy.kind.moveSpeed
                            else -> 0f
                        }
                        enemy.copy(
                            vx = approachValue(enemy.vx, targetVx, config.chaseAcceleration * dt),
                            facing = dirToTarget,
                            stateTimer = t
                        )
                    }
                }
            }

            EnemyBehaviorState.WINDUP -> {
                val windupDur = if (enemy.comboStep == 0) config.windupDuration else config.comboWindupDuration
                if (t >= windupDur) {
                    val dir = enemy.facing.sign.toFloat()
                    if (config.isRanged) {
                        actions.add(
                            EastBlueAiAction.FireRifle(
                                muzzleX = enemy.x + dir * 14f,
                                muzzleY = enemy.y - 13f,
                                facing = enemy.facing,
                                damage = config.baseDamage
                            )
                        )
                        enemy.copy(
                            behavior = EnemyBehaviorState.ATTACK,
                            stateTimer = 0f,
                            vx = dir * config.attackLungeSpeed,
                            attackHitApplied = true
                        )
                    } else {
                        actions.add(EastBlueAiAction.PlaySwingSfx)
                        enemy.copy(
                            behavior = EnemyBehaviorState.ATTACK,
                            stateTimer = 0f,
                            vx = dir * config.attackLungeSpeed,
                            attackHitApplied = false
                        )
                    }
                } else {
                    val aimFacing = if (config.isRanged || config.maxComboSteps > 1) dirToTarget else enemy.facing
                    enemy.copy(
                        vx = approachValue(enemy.vx, 0f, 540f * dt),
                        facing = aimFacing,
                        stateTimer = t
                    )
                }
            }

            EnemyBehaviorState.ATTACK -> {
                var hitApplied = enemy.attackHitApplied
                val hitStart = if (config.maxComboSteps > 1) 0.02f else 0.03f
                if (!config.isRanged && !hitApplied && t >= hitStart) {
                    val slashBox = createMeleeBox(enemy)
                    if (slashBox.intersects(target.hurtbox)) {
                        hitApplied = true
                        actions.add(
                            EastBlueAiAction.MeleeHit(
                                damage = if (enemy.comboStep == 0) config.baseDamage else config.comboDamage,
                                knockbackDir = enemy.facing.sign.toFloat(),
                                shakeIntensity = config.hitShakeIntensity,
                                hitStopSeconds = config.hitStopSeconds
                            )
                        )
                    }
                }
                if (t >= config.attackDuration) {
                    if (!config.isRanged && enemy.comboStep + 1 < config.maxComboSteps) {
                        enemy.copy(
                            behavior = EnemyBehaviorState.WINDUP,
                            stateTimer = 0f,
                            comboStep = enemy.comboStep + 1,
                            facing = dirToTarget,
                            attackHitApplied = false
                        )
                    } else {
                        enemy.copy(
                            behavior = EnemyBehaviorState.RECOVER,
                            stateTimer = 0f,
                            comboStep = 0,
                            attackCooldown = config.attackCooldown,
                            attackHitApplied = hitApplied
                        )
                    }
                } else {
                    enemy.copy(
                        vx = approachValue(enemy.vx, 0f, 380f * dt),
                        stateTimer = t,
                        attackHitApplied = hitApplied
                    )
                }
            }

            EnemyBehaviorState.RECOVER -> {
                if (t >= config.recoverDuration) {
                    val nextState = if (absDx > config.loseAggroRange) {
                        EnemyBehaviorState.PATROL
                    } else {
                        EnemyBehaviorState.CHASE
                    }
                    enemy.copy(behavior = nextState, stateTimer = 0f)
                } else {
                    enemy.copy(
                        vx = approachValue(enemy.vx, 0f, 500f * dt),
                        stateTimer = t
                    )
                }
            }

            EnemyBehaviorState.HURT, EnemyBehaviorState.STUNNED -> {
                enemy.copy(behavior = EnemyBehaviorState.CHASE, stateTimer = 0f)
            }
        }

        return EastBlueAiStepResult(enemy = nextEnemy, actions = actions)
    }

    private fun isTargetEngaged(target: LuffyState, absDx: Float, detectRange: Float): Boolean {
        if (!target.isAlive) return false
        val isTrackedHero = target.activeHero == PlayableHero.LUFFY ||
            target.activeHero == PlayableHero.ZORO ||
            target.activeHero in PlayableHero.entries
        return isTrackedHero && absDx <= detectRange
    }

    private fun stepPatrol(enemy: EnemyState, dt: Float, nextStateTimer: Float): EnemyState {
        var pDir = if (enemy.patrolDir >= 0) 1 else -1
        val maxPatrolX = (enemy.patrolOriginX + config.patrolRadius).coerceAtMost(WorldConstants.RIGHT_BOUNDARY_X - 12f)
        val minPatrolX = (enemy.patrolOriginX - config.patrolRadius).coerceAtLeast(WorldConstants.LEFT_BOUNDARY_X + 12f)
        if (enemy.x >= maxPatrolX) pDir = -1
        if (enemy.x <= minPatrolX) pDir = 1
        val facing = if (pDir > 0) FacingDirection.RIGHT else FacingDirection.LEFT
        return enemy.copy(
            vx = approachValue(enemy.vx, pDir * enemy.kind.moveSpeed * config.patrolSpeedFactor, 400f * dt),
            facing = facing,
            patrolDir = pDir,
            stateTimer = nextStateTimer
        )
    }

    private fun createMeleeBox(enemy: EnemyState): Rect2D {
        val boxX = if (enemy.facing == FacingDirection.RIGHT) {
            enemy.x + 2f
        } else {
            enemy.x - 2f - config.meleeReach
        }
        return Rect2D(
            x = boxX,
            y = enemy.y - config.meleeHeight - 2f,
            width = config.meleeReach,
            height = config.meleeHeight
        )
    }

    private fun approachValue(value: Float, target: Float, delta: Float): Float = when {
        value < target -> (value + delta).coerceAtMost(target)
        value > target -> (value - delta).coerceAtLeast(target)
        else -> target
    }
}


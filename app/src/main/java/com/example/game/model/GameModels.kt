 * Complete player state in virtual pixel world coordinates (supports live tag-team switching
 * between Luffy, Zoro, Sanji, Nami & Usopp with independent HP & cooldowns).
 * (x, y) represents the bottom-center anchor (feet) for rock-solid ground contact.
 */
data class LuffyState(
    val id: String = "luffy",
    val activeHero: PlayableHero = PlayableHero.LUFFY,
    val heroHp: Map<PlayableHero, Int> = PlayableHero.entries.associateWith { it.maxHp },
    val x: Float = 240f,
    val y: Float = WorldConstants.BEACH_GROUND_Y,
    val vx: Float = 0f,
    val vy: Float = 0f,
    val facing: FacingDirection = FacingDirection.RIGHT,
    val isGrounded: Boolean = true,
    val airJumpsRemaining: Int = 1,
    val maxHp: Int = 100,
    val currentHp: Int = 100,
    val invulnTimer: Float = 0f,
    val hurtTimer: Float = 0f,
    val switchCooldown: Float = 0f,
    val switchFlashTimer: Float = 0f,
    val berries: Int = 0,
    val defeatedCount: Int = 0,
    val coyoteTimer: Float = 0f,
    val jumpBufferTimer: Float = 0f,
    val landTimer: Float = 0f,
    val animState: PlayerAnimState = PlayerAnimState.IDLE,
    val animTime: Float = 0f,
    val activeAttack: AttackType? = null,
    val attackPhase: AttackPhase = AttackPhase.NONE,
    val attackTimer: Float = 0f,
    val attackHitTargets: Set<String> = emptySet(),
    val gatlingHitPulseTimer: Float = 0f,
    val stretchFactor: Float = 0f,
    val axeImpactTriggered: Boolean = false,
    val gatlingSpawnAccum: Float = 0f,
    val gatlingGhosts: List<GatlingPunchGhost> = emptyList(),
    val zoroComboStep: Int = 0,
    val zoroComboResetTimer: Float = 0f,
    val onigiriSlashTriggered: Boolean = false,
    val onigiriGhostAccum: Float = 0f,
    val sanjiComboStep: Int = 0,
    val sanjiComboResetTimer: Float = 0f,
    val diableExplosionTriggered: Boolean = false,
    val chopperComboStep: Int = 0,
    val chopperComboResetTimer: Float = 0f,
    val guardHealTriggered: Boolean = false,
    val monsterRoarTriggered: Boolean = false,
    val monsterSlamTriggered: Boolean = false,
    val attackFired: Boolean = false,
    val cooldowns: Map<AttackType, CooldownState> = AttackType.entries.associateWith {
        CooldownState(0f, it.cooldownSeconds)
    },
    val stepSoundTimer: Float = 0f,
    // Luffy Gear 4: Boundman transformation state
    val gear4Meter: Float = 0f,
    val gear4Active: Boolean = false,
    val gear4Timer: Float = 0f,
    val gear4BounceTimer: Float = 0f,
    val kingKongImpactTriggered: Boolean = false,
    // Zoro King of Hell (Black Bandana) Awakening & Steel Parry state
    val zoroHellMeter: Float = 0f,
    val zoroHellActive: Boolean = false,
    val zoroHellTimer: Float = 0f,
    val zoroParryCritReady: Boolean = false,
    val purgatoryDashStage: Int = 0,
    val asuraSlashesTriggered: Boolean = false
) {
    val isAlive: Boolean get() = currentHp > 0

    /**
     * Next alive hero in cyclic order LUFFY -> ZORO -> SANJI -> NAMI -> USOPP -> LUFFY.
     */
    val standbyHero: PlayableHero
        get() {
            val all = PlayableHero.entries
            val cur = activeHero.ordinal
            for (step in 1 until all.size) {
                val candidate = all[(cur + step) % all.size]
                if ((heroHp[candidate] ?: 0) > 0) return candidate
            }
            return all[(cur + 1) % all.size]
        }

    val standbyHp: Int
        get() = heroHp[standbyHero] ?: 0

    val hurtbox: Rect2D
        get() = if (activeHero == PlayableHero.CHOPPER && activeAttack != AttackType.CHOPPER_MONSTER_POINT) {
            // Compact Brain Point reindeer hurtbox — enemy shots fly over Chopper's hat!
            Rect2D(
                x = x - 6.5f,
                y = y - 19f,
                width = 13f,
                height = 19f
            )
        } else {
            Rect2D(
                x = x - 8f,
                y = y - 28f,
                width = 16f,
                height = 28f
            )
        }
}

